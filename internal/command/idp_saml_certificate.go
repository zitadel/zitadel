package command

import (
	"crypto/rsa"
	"crypto/x509"
	"encoding/pem"
	"time"

	"github.com/zitadel/zitadel/internal/zerrors"
)

// certificateAndKey returns the validated key and certificate of the provider.
// If neither was provided, nil is returned for both.
func (p *SAMLProvider) certificateAndKey() (key, certificate []byte, err error) {
	if len(p.Certificate) == 0 && len(p.Key) == 0 {
		return nil, nil, nil
	}
	return samlCertificateAndKey(p.Certificate, p.Key, time.Now())
}

// samlCertificateAndKey validates the provided PEM encoded certificate (chain) and private key
// and returns them in the same format as generated by samlCertificateAndKeyGenerator.
// The first certificate is used as the SP certificate, any following certificates are kept as chain.
func samlCertificateAndKey(certificate, key []byte, now time.Time) ([]byte, []byte, error) {
	if len(certificate) == 0 {
		return nil, nil, zerrors.ThrowInvalidArgument(nil, "COMMAND-s45bsj7m2u", "Errors.IDP.SAMLCertificateMissing")
	}
	if len(key) == 0 {
		return nil, nil, zerrors.ThrowInvalidArgument(nil, "COMMAND-ru47reo7oq", "Errors.IDP.PrivateKeyMissing")
	}

	var certs []*x509.Certificate
	for block, rest := pem.Decode(certificate); block != nil; block, rest = pem.Decode(rest) {
		if block.Type != "CERTIFICATE" {
			continue
		}
		cert, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			return nil, nil, zerrors.ThrowInvalidArgument(err, "COMMAND-ko5hxclbqm", "Errors.IDP.SAMLCertificateInvalid")
		}
		certs = append(certs, cert)
	}
	if len(certs) == 0 {
		return nil, nil, zerrors.ThrowInvalidArgument(nil, "COMMAND-khszemchha", "Errors.IDP.SAMLCertificateInvalid")
	}
	leaf := certs[0]
	if now.Before(leaf.NotBefore) || now.After(leaf.NotAfter) {
		return nil, nil, zerrors.ThrowInvalidArgument(nil, "COMMAND-3in4sinihu", "Errors.IDP.SAMLCertificateExpired")
	}

	privateKey, err := parseRSAPrivateKey(key)
	if err != nil {
		return nil, nil, err
	}
	publicKey, ok := leaf.PublicKey.(*rsa.PublicKey)
	if !ok || !publicKey.Equal(&privateKey.PublicKey) {
		return nil, nil, zerrors.ThrowInvalidArgument(nil, "COMMAND-b3wng4a4hi", "Errors.IDP.SAMLCertificateKeyMismatch")
	}

	var certPEM []byte
	for _, cert := range certs {
		certPEM = append(certPEM, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: cert.Raw})...)
	}
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "RSA PRIVATE KEY", Bytes: x509.MarshalPKCS1PrivateKey(privateKey)})
	return keyPEM, certPEM, nil
}

// parseRSAPrivateKey parses the first PEM encoded private key in PKCS#1 or PKCS#8 format.
// Only RSA keys are supported, as they are required for signing and decryption of SAML messages.
func parseRSAPrivateKey(key []byte) (*rsa.PrivateKey, error) {
	for block, rest := pem.Decode(key); block != nil; block, rest = pem.Decode(rest) {
		switch block.Type {
		case "RSA PRIVATE KEY":
			privateKey, err := x509.ParsePKCS1PrivateKey(block.Bytes)
			if err != nil {
				return nil, zerrors.ThrowInvalidArgument(err, "COMMAND-hadzypzq6y", "Errors.IDP.InvalidPrivateKey")
			}
			return privateKey, nil
		case "PRIVATE KEY":
			parsed, err := x509.ParsePKCS8PrivateKey(block.Bytes)
			if err != nil {
				return nil, zerrors.ThrowInvalidArgument(err, "COMMAND-tr2sns7tdq", "Errors.IDP.InvalidPrivateKey")
			}
			privateKey, ok := parsed.(*rsa.PrivateKey)
			if !ok {
				return nil, zerrors.ThrowInvalidArgument(nil, "COMMAND-qv3lw8t2ze", "Errors.IDP.InvalidPrivateKey")
			}
			return privateKey, nil
		}
	}
	return nil, zerrors.ThrowInvalidArgument(nil, "COMMAND-n6c1ub0yfk", "Errors.IDP.InvalidPrivateKey")
}
